/**
 * PDP-3 B4 — preview-confirm gate tests.
 *
 * Covers the new `awaiting_push_confirm` stage and the
 * `confirmPush` / `cancelPush` orchestrator methods:
 *   - Gate is on by default (AUTO_PUSH_AFTER_PROTO=false): Proto runs in
 *     dryRun mode, scaffold lands in protoOutput, pipeline halts.
 *   - Confirm: cached files are pushed via pushScaffoldFiles (no LLM
 *     regeneration), pipeline transitions to trace_testing → completed.
 *   - Cancel: pipeline transitions to completed_partial; protoOutput is
 *     preserved so the user can still inspect / copy the code.
 *   - Auto-push override (AUTO_PUSH_AFTER_PROTO=true): the gate is bypassed
 *     and the legacy flow is preserved.
 *   - Idempotency: double-clicking Confirm/Cancel is safe.
 *   - Stage rejection: confirmPush / cancelPush only accept the gate stage.
 */

