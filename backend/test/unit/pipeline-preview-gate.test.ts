function createMockScribe(): ScribeAgent {
  return {
    createInitialState() {
      return {
        idea: 'todo',
        conversation: [],
        clarificationRound: 0,
        phase: 'clarifying' as const,
        pendingQuestionIds: [],
        answeredQuestionIds: [],
      };
    },
    analyzIdea: async () => ({ type: 'spec' as const, data: mockScribeOutput }),
    processUserAnswer(_state: ScribeState, _answer: string) {},
    continueAfterAnswer: async () => ({ type: 'spec' as const, data: mockScribeOutput }),
    regenerateSpec: async () => ({ type: 'spec' as const, data: mockScribeOutput }),
    generateSpec: async () => ({ type: 'spec' as const, data: mockScribeOutput }),
  } as unknown as ScribeAgent;
}

function createMockProto(opts?: {
  execute?: (input: unknown) => Promise<ProtoResult>;
  pushScaffoldFiles?: (...args: unknown[]) => Promise<ProtoResult>;
}): ProtoAgent {
  return {
    execute:
      opts?.execute ??
      (async (input: { dryRun?: boolean }) => {
        // Echo whatever Proto would return — committed:false when dryRun
        // mirrors the real dryRun path in ProtoAgent.execute.
        if (input.dryRun) {
          return { type: 'output' as const, data: dryRunProtoOutput };
        }
        return { type: 'output' as const, data: pushedProtoOutput };
      }),
    pushScaffoldFiles:
      opts?.pushScaffoldFiles ??
      (async () => ({ type: 'output' as const, data: pushedProtoOutput })),
  } as unknown as ProtoAgent;
}

function createMockTrace(opts?: {
  execute?: (input: unknown) => Promise<{ type: 'output'; data: TraceOutput }>;
}): TraceAgent {
  return {
    execute: opts?.execute ?? (async () => ({ type: 'output' as const, data: mockTraceOutput })),
  } as unknown as TraceAgent;
}

function createOrchestrator(overrides?: {
  store?: PipelineStore;
  proto?: ProtoAgent;
  trace?: TraceAgent;
  emit?: (event: PipelineEvent) => void;
}) {
  const store = overrides?.store ?? new InMemoryStore();
  return {
    store,
    orchestrator: new PipelineOrchestrator(
      store,
      createMockScribe(),
      overrides?.proto ?? createMockProto(),
      overrides?.trace ?? createMockTrace(),
      async () => 'testuser',
      async () => 'ghp_mock_token',
      () => ({
        createRepository: async (_o: string, name: string) => ({
          url: `https://github.com/test/${name}`,
        }),
        createBranch: async () => {},
        commitFile: async () => {},
        pushFiles: async () => {},
        createPR: async () => ({ url: '' }),
        listFiles: async () => [] as string[],
        getFileContent: async () => '',
      }),
      overrides?.emit
    ),
  };
}

// ─── Gate ON (default): scaffold → awaiting_push_confirm ──

describe('B4 Preview Gate — gate ON (default)', () => {
  it('halts at awaiting_push_confirm after Proto generation (no auto-push)', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const executeCalls: Array<{ dryRun?: boolean }> = [];
    const proto = createMockProto({
      execute: async (input: unknown) => {
        executeCalls.push(input as { dryRun?: boolean });
        return { type: 'output' as const, data: dryRunProtoOutput };
      },
    });
    const { orchestrator, store } = createOrchestrator({ proto });

    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'React todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');

    const gated = await waitForStage(store, started.id, ['awaiting_push_confirm']);
    assert.equal(gated.stage, 'awaiting_push_confirm');
    assert.ok(gated.protoOutput, 'protoOutput should be persisted at gate stage');
    // PR-V-spec-artifacts: orchestrator injects docs/PRD.md + docs/TECHNICAL-ANALYSIS.md
    // alongside Proto's 2 scaffold files → 4 cached files total.
    assert.equal(gated.protoOutput?.files.length, 4, 'cached files visible to FE preview');
    const cachedPaths = gated.protoOutput?.files.map((f) => f.filePath) ?? [];
    assert.ok(cachedPaths.includes('docs/PRD.md'));
    assert.ok(cachedPaths.includes('docs/TECHNICAL-ANALYSIS.md'));
    assert.equal(executeCalls.length, 1);
    assert.equal(executeCalls[0]?.dryRun, true, 'Proto must be called with dryRun:true');
  });

  // PR-F2 (2026-05-19) — Trace must run BEFORE awaiting_push_confirm.
  it('runs Trace in dryRun mode BEFORE awaiting_push_confirm (PR-F2)', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const traceCalls: Array<{
      dryRun?: boolean;
      inputFiles?: Array<{ filePath: string; content: string }>;
      repo?: string;
    }> = [];
    const trace = createMockTrace({
      execute: async (input: unknown) => {
        const i = input as {
          dryRun?: boolean;
          inputFiles?: Array<{ filePath: string; content: string }>;
          repo?: string;
        };
        traceCalls.push({ dryRun: i.dryRun, inputFiles: i.inputFiles, repo: i.repo });
        return { type: 'output' as const, data: mockTraceOutput };
      },
    });
    const { orchestrator, store } = createOrchestrator({ trace });

    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'React todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');

    const gated = await waitForStage(store, started.id, ['awaiting_push_confirm']);
    assert.equal(gated.stage, 'awaiting_push_confirm');
    // Trace MUST have run exactly once, in dryRun mode, with Proto's
    // local inputFiles (no GitHub fetch).
    assert.equal(traceCalls.length, 1, 'Trace runs once BEFORE the push gate');
    assert.equal(traceCalls[0]?.dryRun, true, 'Trace called with dryRun:true');
    // PR-V-spec-artifacts: Trace inputFiles now also include the injected
    // docs/PRD.md + docs/TECHNICAL-ANALYSIS.md artifacts (2 source + 2 docs).
    assert.ok(
      traceCalls[0]?.inputFiles && traceCalls[0].inputFiles.length === 4,
      "Trace receives Proto's in-memory files (incl. injected docs/*) as inputFiles"
    );
    assert.ok(gated.traceOutput, 'traceOutput persisted at push gate');
    assert.equal(
      gated.traceOutput?.testSummary?.coveragePercentage,
      100,
      'AC coverage visible at gate stage'
    );
  });

  it('cancelPush → completed_partial; protoOutput stays for inspection', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const { orchestrator, store } = createOrchestrator();
    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'React todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');
    await waitForStage(store, started.id, ['awaiting_push_confirm']);

    const cancelled = await orchestrator.cancelPush(started.id);
    assert.equal(cancelled.stage, 'completed_partial');
    assert.ok(cancelled.protoOutput, 'protoOutput preserved so user can still copy files');
    // PR-V-spec-artifacts: 2 source + 2 injected doc artifacts.
    assert.equal(cancelled.protoOutput?.files.length, 4);
  });

  it('confirmPush → pushScaffoldFiles → completed (Trace already ran pre-gate, PR-F2)', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const pushCalls: Array<{ owner: string; repo: string; fileCount: number }> = [];
    const proto = createMockProto({
      execute: async () => ({ type: 'output' as const, data: dryRunProtoOutput }),
      pushScaffoldFiles: async (...args: unknown[]) => {
        const [owner, repo, , files] = args as [string, string, unknown, ProtoOutput['files']];
        pushCalls.push({ owner, repo, fileCount: files.length });
        return { type: 'output' as const, data: pushedProtoOutput };
      },
    });
    // PR-F2: count Trace calls so we can prove Trace runs ONCE (pre-gate)
    // and is not invoked again after the user confirms the push.
    const traceCalls: Array<{ dryRun?: boolean }> = [];
    const trace = createMockTrace({
      execute: async (input: unknown) => {
        traceCalls.push(input as { dryRun?: boolean });
        return { type: 'output' as const, data: mockTraceOutput };
      },
    });
    const { orchestrator, store } = createOrchestrator({ proto, trace });

    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'React todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');
    await waitForStage(store, started.id, ['awaiting_push_confirm']);

    // Sanity: Trace already ran in dryRun BEFORE the gate.
    assert.equal(traceCalls.length, 1, 'Trace runs once pre-gate in dryRun mode');
    assert.equal(traceCalls[0]?.dryRun, true);

    await orchestrator.confirmPush(started.id);
    const completed = await waitForStage(store, started.id, ['completed']);
    assert.equal(completed.stage, 'completed');
    assert.equal(pushCalls.length, 1, 'pushScaffoldFiles called once');
    assert.equal(pushCalls[0]?.owner, 'testuser');
    assert.equal(pushCalls[0]?.repo, 'my-todo');
    // PR-V-spec-artifacts: pushScaffoldFiles receives 2 source + 2 injected docs.
    assert.equal(pushCalls[0]?.fileCount, 4);
    // After push, protoOutput.branch should be the real "main", not "dry-run"
    assert.equal(completed.protoOutput?.branch, 'main');
    // PR-F2: Trace must NOT be invoked again on push confirmation.
    assert.equal(traceCalls.length, 1, 'Trace does NOT run again on confirmPush');
    // The pre-gate traceOutput stays intact.
    assert.ok(completed.traceOutput, 'traceOutput from pre-gate dryRun preserved');
  });

  it('confirmPush is idempotent — second call returns current state', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const { orchestrator, store } = createOrchestrator();
    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'Todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');
    await waitForStage(store, started.id, ['awaiting_push_confirm']);

    await orchestrator.confirmPush(started.id);
    // Wait for push to settle then call again
    await waitForStage(store, started.id, ['completed']);
    const second = await orchestrator.confirmPush(started.id);
    assert.equal(second.stage, 'completed', 'idempotent — already past gate');
  });

  it('cancelPush is idempotent on terminal state', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const { orchestrator, store } = createOrchestrator();
    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'Todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');
    await waitForStage(store, started.id, ['awaiting_push_confirm']);

    await orchestrator.cancelPush(started.id);
    const second = await orchestrator.cancelPush(started.id);
    assert.equal(second.stage, 'completed_partial');
  });

  it('confirmPush rejected when not at gate stage', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const { orchestrator, store } = createOrchestrator();
    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'Todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    // Spec not yet approved → still at awaiting_approval, cannot confirmPush
    await assert.rejects(() => orchestrator.confirmPush(started.id), { message: /Invalid stage/ });
  });

  it('cancelPush rejected when not at gate stage', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const { orchestrator, store } = createOrchestrator();
    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'Todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await assert.rejects(() => orchestrator.cancelPush(started.id), { message: /Invalid stage/ });
  });

  it('emits stage_change event for awaiting_push_confirm', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();

    const events: PipelineEvent[] = [];
    const { orchestrator, store } = createOrchestrator({
      emit: (event) => events.push(event),
    });
    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'Todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');
    await waitForStage(store, started.id, ['awaiting_push_confirm']);

    const stages = events.filter((e) => e.type === 'stage_change').map((e) => e.stage);
    assert.ok(stages.includes('awaiting_push_confirm'), 'gate stage_change event emitted');
  });
});

// ─── Gate OFF (auto-push): legacy flow preserved ─────────

describe('B4 Preview Gate — gate OFF (AUTO_PUSH_AFTER_PROTO=true)', () => {
  it('bypasses gate when env is set, Proto runs without dryRun', async () => {
    process.env.AUTO_PUSH_AFTER_PROTO = 'true';
    __clearEnvCacheForTests();

    const executeCalls: Array<{ dryRun?: boolean }> = [];
    const pushScaffoldCalls: number[] = [];
    const proto = createMockProto({
      execute: async (input: unknown) => {
        executeCalls.push(input as { dryRun?: boolean });
        return { type: 'output' as const, data: pushedProtoOutput };
      },
      pushScaffoldFiles: async () => {
        pushScaffoldCalls.push(1);
        return { type: 'output' as const, data: pushedProtoOutput };
      },
    });
    const { orchestrator, store } = createOrchestrator({ proto });

    const started = await orchestrator.startPipeline(
      'user-1',
      { idea: 'Todo app' },
      undefined,
      undefined,
      undefined,
      undefined,
      true /* traceEnabled */
    );
    await waitForStage(store, started.id, ['awaiting_approval']);
    await orchestrator.approveSpec(started.id, 'my-todo', 'private');

    const completed = await waitForStage(store, started.id, ['completed']);
    assert.equal(completed.stage, 'completed');
    assert.equal(executeCalls.length, 1);
    assert.equal(executeCalls[0]?.dryRun, false, 'auto-push path runs Proto with dryRun:false');
    assert.equal(pushScaffoldCalls.length, 0, 'auto-push path skips pushScaffoldFiles helper');

    // Reset so subsequent tests in other files see the default
    process.env.AUTO_PUSH_AFTER_PROTO = 'false';
    __clearEnvCacheForTests();
  });
});
